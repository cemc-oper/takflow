# --- build-info provider injection -------------------------------------------

_build_info_provider: Optional[Callable[[], Dict[str, str]]] = None


def set_build_info_provider(provider: Callable[[], Dict[str, str]]) -> None:
    """Register an app callback returning the ``{"warning","info"}`` header dict.

    Called by the app (e.g. on ``import mcv_workflow.job``) so rendered headers
    carry the app's branding. When unset, a generic ``takflow`` header is used.
    """
    global _build_info_provider
    _build_info_provider = provider


def _current_build_info_lines() -> Dict[str, str]:
    scoped = _scoped_lines.get()
    if scoped is not None:
        return dict(scoped)
    if _build_info_provider is not None:
        return _build_info_provider()
    return _generic_build_info_lines(_generic_build_info("unknown"), "takflow")


def _job_resource_spec(
    job_type="serial", *, queue=None, nodes=None, ntasks_per_node=None, time=None,
    memory=None, requeue=None, job_name=None, output=None, error=None,
    project=None, application=None, scheduler="slurm", exclusive=None,
) -> ResourceSpec:
    task = TaskResource(job_type=job_type, queue=queue, nodes=nodes, ntasks_per_node=ntasks_per_node,
                        time=time, memory=memory, requeue=requeue, job_name=job_name, output=output, error=error)
    workload = None if scheduler == "local" else SlurmWorkload(project=project or "", application=application)
    fields = task.compile(workload).model_dump()
    fields.update(scheduler=scheduler, project=project, application=application, exclusive=exclusive)
    return ResourceSpec(**fields)


def _ecflow_optional_line(variable: str, line: str, default_line: str | None = None) -> str:
    """Select a header line during native job creation.

    Inside %comment ecFlow tolerates a missing reference. Only a successful
    substitution unescapes %%end and %%comment before comment removal.
    """
    ref = f"%{variable}%"
    # Resolve a supplied value outside %comment too, so a broken reference in
    # its value fails job creation. Resetting the delimiter emits no job text.
    lines = [f"%%ecfmicro %% %{variable}:%", "%comment", f"%%end {ref}", line, f"%%comment {ref}"]
    if default_line is not None:
        # When the override resolved, keep the same comment open across the
        # default by temporarily changing its closing delimiter. Restore %
        # before the next job line. No scalar is interpreted as a directive.
        lines.extend((f"%%ecfmicro @ {ref}", "%end", default_line, "%comment", "@ecfmicro %"))
    lines.append("%end")
    return "\n".join(lines)


def _resource_directive(field: str, variable: str, fallback, mode: str, native_slurm: bool) -> str:
    key = field.replace("_", "-")
    prefix = f"#ORVIX {key}="
    if isinstance(fallback, bool):
        fallback = str(fallback).lower()
    if mode == "ecflow":
        if field == "requeue" and (native_slurm or fallback is None):
            fragment = "requeue" if native_slurm else "orvix-requeue"
            return f"%include <common/{fragment}-%REQUEUE:{fallback or 'unset'}%.h>"
        ref = f"%{variable}%" if fallback is None else f"%{variable}:{fallback}%"
        if native_slurm:
            line = slurm_directive(field, ref, engine_reference=True)
        elif field == "job_name" or (fallback is not None and any(c.isspace() for c in str(fallback))):
            line = f'{prefix}"{ref}"'
        else:
            line = prefix + ref
        return _ecflow_optional_line(variable, line) if fallback is None else line
    else:
        expression = variable
        if fallback is not None:
            expression += f" | default({str(fallback)!r})"
        if field == "requeue":
            expression += " | lower"
        ref = "{{ " + expression + " }}"
        if fallback is None:
            if field == "job_name":
                ref = '"' + ref + '"'
            return ("{% if " + variable + " is defined and " + variable + " is not none %}"
                    + prefix + ref + "{% endif %}")
    if field == "job_name" or (fallback is not None and any(c.isspace() for c in str(fallback))):
        ref = '"' + ref + '"'
    return prefix + ref


def _engine_log_directive(field: str, fallback: str | None, mode: str, native_slurm: bool) -> str:
    """Keep the engine's job log expression available until job creation."""
    variable = RESOURCE_VARIABLES[field]
    if mode == "ecflow":
        def log_line(value):
            if native_slurm:
                return slurm_directive(field, value, engine_reference=True)
            return f'#ORVIX {field}="{value}"'

        if fallback is not None and "%" not in fallback:
            return log_line(f"%{variable}:{fallback}%")
        default = log_line(ecflow_log_value(fallback)) if fallback is not None else None
        return _ecflow_optional_line(variable, log_line(f"%{variable}%"), default)
    path = variable + ' | replace("{{ TAKLER_JOBOUT }}", TAKLER_JOBOUT | default(""))'
    line = f'#ORVIX {field}="{{{{ {path} }}}}"'
    default = f'{{% else %}}#ORVIX {field}="{fallback}"' if fallback is not None else ""
    return f"{{% if {variable} is defined and {variable} is not none %}}{line}{default}{{% endif %}}"


def _workflow_resource_block(spec: ResourceSpec, mode: str | None, job_type: str, *, native_slurm=False) -> str:
    if native_slurm and mode == "takler":
        raise ValueError("native Slurm resource headers support ecFlow and Shell")
    engine = mode in ("ecflow", "takler")
    lines = []
    for field in CANONICAL_KEYS:
        value = getattr(spec, field)
        if engine and field in ("output", "error"):
            lines.append(_engine_log_directive(field, value, mode, native_slurm))
            continue
        if engine and field in RESOURCE_VARIABLES:
            if job_type != "serial" or field not in ("nodes", "ntasks_per_node"):
                lines.append(_resource_directive(field, RESOURCE_VARIABLES[field], value, mode, native_slurm))
            continue
        if value is None:
            continue
        if native_slurm:
            line = slurm_directive(field, value, engine_reference=engine)
        elif field == "scheduler":
            line = f"#ORVIX scheduler={value}"
        else:
            line = orvix_directive(field, value)
        if line:
            lines.append(line)
    return "\n".join(lines)


def render_orvix_resource_block(
    job_type: str = "serial",
    queue: Optional[str] = None,
    partition: Optional[str] = None,
    nodes: Optional[Union[int, str]] = None,
    ntasks_per_node: Optional[Union[int, str]] = None,
    time: Optional[str] = None,
    walltime: Optional[str] = None,
    memory: Optional[str] = None,
    output: Optional[str] = None,
    error: Optional[str] = None,
    project: Optional[str] = None,
    wckey: Optional[str] = None,
    application: Optional[str] = None,
    scheduler: str = "slurm",
    requeue: Optional[bool] = None,
    workflow_mode: Optional[str] = None,
    *, job_name: str | None = None, exclusive: bool | str | None = None,
) -> str:
    """Render ORVIX directives with the existing optional input aliases."""
    spec = _job_resource_spec(
        job_type, queue=resolve_resource_alias("queue", queue, "partition", partition, nonblank=True),
        time=resolve_resource_alias("time", time, "walltime", walltime, nonblank=True),
        project=resolve_resource_alias("project", project, "wckey", wckey), nodes=nodes,
        ntasks_per_node=ntasks_per_node, memory=memory, output=output, error=error,
        application=application, scheduler=scheduler, requeue=requeue, job_name=job_name, exclusive=exclusive,
    )
    block = _workflow_resource_block(spec, workflow_mode, job_type)
    for name, value in (("partition", partition), ("walltime", walltime), ("wckey", wckey)):
        if value is not None:
            warnings.warn(RESOURCE_ALIAS_HINTS[f"render_orvix_resource_block.{name}"], ResourceAliasWarning, stacklevel=2)
    return block


def render_slurm_resource_block(*, job_type="serial", workflow_mode=None, **resources) -> str:
    """Render the supported native Slurm header fields using canonical input names."""
    return _workflow_resource_block(_job_resource_spec(job_type, **resources), workflow_mode, job_type,
                                    native_slurm=True)


def _workflow_resource_defaults(context, resources):
    config = context["config"]
    workload = config.workload
    job_type = resources.get("job_type", "serial")
    if resources.get("queue") is None and resources.get("partition") is None:
        resources["queue"] = getattr(workload, f"default_{job_type}_queue", None)
    if resources.get("project") is None and resources.get("wckey") is None:
        resources["project"] = getattr(workload, "project", None)
    if resources.get("application") is None:
        resources["application"] = getattr(workload, "application", None)
    resources.setdefault("scheduler", getattr(workload, "scheduler", "local"))
    for field, name in (("output", "output_std_log_path"), ("error", "output_stderr_log_path")):
        if resources.get(field) is None:
            resources[field] = context.get(name)
    resources["workflow_mode"] = config.workflow_mode
    return resources


@pass_context
def _render_workflow_orvix_resource_block(context, **resources) -> str:
    return render_orvix_resource_block(**_workflow_resource_defaults(context, resources))


@pass_context
def _render_workflow_slurm_resource_block(context, **resources) -> str:
    return render_slurm_resource_block(**_workflow_resource_defaults(context, resources))


RESOURCE_TEMPLATE_HELPERS = {
    "render_orvix_resource_block": _render_workflow_orvix_resource_block,
    "render_slurm_resource_block": _render_workflow_slurm_resource_block,
}


# --- rendering ---------------------------------------------------------------

def _runtime_reference(value: str) -> bool:
    return any(marker in value for marker in ("$", "%", "{{", "{%", "://"))


def _check_script_reference(
    script_path: str, output_repo_base: str, config: "BaseWorkflowConfig",
    report: GenerationCheckReport, *, helper: str, stage: str,
) -> None:
    dynamic = _runtime_reference(script_path)
    script_file = check_relative_path(output_repo_base, script_path, stage=stage,
                                      report=report, object=helper if dynamic else None)
    if dynamic:
        report.unchecked("GEN_SCRIPT_DYNAMIC", stage, helper,
                         "script location contains an unresolved runtime or remote reference")
        return
    check_input_file(
        script_file, stage=stage, report=report,
        executable=helper == "invoke_script" and config.script_invoke_mode != "inline",
    )


def _template_file(env: Environment, name: str) -> Optional[Path]:
    if isinstance(env.loader, FileSystemLoader):
        return next((Path(root, name) for root in env.loader.searchpath
                     if Path(root, name).is_file()), None)
    return None


class _JobTemplateLoader(FileSystemLoader):
    """Guard files selected by real Jinja control flow before reading them."""

    def __init__(self, search_paths, report: GenerationCheckReport):
        super().__init__(search_paths)
        self._report = report

    def get_source(self, environment: Environment, template: str):
        if Path(template).is_absolute() or ".." in Path(template).parts:
            self._report.fail("GEN_PATH_ESCAPE", "job.render", template, "template reference must stay within its resource roots")
        for root in self.searchpath:
            candidate = Path(root, template)
            if os.path.lexists(candidate):
                path = check_relative_path(root, template, stage="job.render", report=self._report)
                check_input_file(path, stage="job.render", report=self._report)
                break
        return super().get_source(environment, template)


def _job_input_guard(outputs, report: GenerationCheckReport):
    """Index selected destinations once, then check each template or script as it is used."""
    paths = {path.resolve() for path in outputs}
    identities = {}
    for path in paths:
        if path.is_file():
            metadata = path.stat()
            identities[(metadata.st_dev, metadata.st_ino)] = path

    def protect(source: Path) -> None:
        resolved = source.resolve()
        target = resolved if resolved in paths else None
        if target is None and identities and source.is_file():
            metadata = source.stat()
            target = identities.get((metadata.st_dev, metadata.st_ino))
        if target is not None:
            report.fail("GEN_INPUT_OUTPUT_OVERLAP", "job.preflight", str(target),
                        "job output would overwrite a known template or script input")

    return protect


def render_jobs_from_directory(
    config: "BaseWorkflowConfig",
    repo_base: Union[str, Path, List[Union[str, Path]]],
    output_repo_base: str,
    job_output_dir: str = "jobs",
    template_filter: Optional[Callable[[Path], bool]] = None,
    *,
    check_report: Optional[GenerationCheckReport] = None,
    environment: Environment | None = None,
    template_context: Mapping | None = None,
    file_mode: int | None = None,
    verbose: bool = True,
    script_input_check: Callable[[str], None] | None = None,
    prepare_outputs: Callable[[list[tuple[Path, Path]]], None] | None = None,
) -> None:
    """Render every ``jobs/**/*.j2`` template under one or more repo roots.

    Parameters
    ----------
    config : BaseWorkflowConfig
        Workflow config used as template data.
    repo_base : str, Path, or list
        One or more repo roots containing ``jobs`` template directories.
        When a list is given, directories are processed in order and later
        directories overwrite earlier ones for identical relative paths.
    output_repo_base : str
        Output repo root.
    job_output_dir : str
        Output subdirectory for rendered job files, relative to
        ``output_repo_base``. The default ``"jobs"`` reproduces the source
        layout (``jobs/<rel>.j2`` -> ``jobs/<rel>.<suffix>``); apps whose
        runtime layout differs (e.g. TYM's ``ecffiles/``) pass their own
        directory name.
    template_filter : callable, optional
        Predicate receiving the template's path relative to its ``jobs/``
        directory (e.g. ``Path("data/initial.sh.j2")``); returning ``False``
        skips the template entirely (no rendering, no output file). Intended
        for feature-toggle-aware generation: apps pass a predicate derived
        from their ``enable_*`` switches so templates of disabled components
        never enter rendering. ``None`` (default) renders everything —
        identical to the previous behaviour.
    check_report : GenerationCheckReport, optional
        Collect generation failures and files written by this invocation.
    script_input_check : callable, optional
        Additional validation of local scripts actually consumed while rendering.
        The standard full build uses this to reject stale prerequisite files.
    """
    report = check_report if check_report is not None else GenerationCheckReport()
    preflight_generation(config, check_report=report)
    if isinstance(repo_base, (str, Path)):
        repo_bases = [str(repo_base)]
    elif isinstance(repo_base, (list, tuple)):
        repo_bases = [str(rb) for rb in repo_base]
    else:
        raise TypeError(
            f"repo_base must be str, Path, or list, got {type(repo_base)}"
        )

    # Collect existing (repo_base, jobs_dir) pairs.  For a single repo_base we
    # preserve the original error-on-missing behaviour; for a list we tolerate
    # sparse layers but fail if nothing is found.
    repo_jobs_pairs = []
    for source_idx, rb in enumerate(repo_bases):
        jobs_dir = Path(rb, "jobs")
        if jobs_dir.is_dir():
            repo_jobs_pairs.append((source_idx, rb, jobs_dir))
        elif len(repo_bases) == 1:
            report.fail("GEN_JOB_DIRECTORY_MISSING", "job.preflight", str(jobs_dir),
                        "jobs directory is unavailable", error_type=GenerationInputError)

    if not repo_jobs_pairs:
        report.fail("GEN_JOB_DIRECTORY_MISSING", "job.preflight", "jobs",
                    "no jobs directory is available in the resource layers",
                    error_type=GenerationInputError)

    def include_raw(script_path: str) -> str:
        script_file = check_relative_path(output_repo_base, script_path, stage="job.render",
                                          report=report)
        protect_input(script_file)
        if script_input_check is not None:
            script_input_check(script_path)
        check_input_file(script_file, stage="job.render", report=report)
        with open(script_file, "r", encoding="utf-8" if environment is not None else None) as f:
            content = f.read()

        # ecflow 模式下需用 %nopp/%end 包裹原生脚本内容，
        # 避免 ecflow 预处理器解析脚本中的 % 指令。
        # 注意：保留与 mcv 原实现一致的 12 空格空行，确保字节级输出不变。
        if config.workflow_mode == "ecflow":
            _pad = " " * 12
            content = f"%nopp\n{_pad}\n{content}\n{_pad}\n%end\n"
        return content

    def invoke_script(script_path: str, *args: str) -> str:
        """Invoke a business script; arguments are literal strings, not shell code.

        Callbacks belong to the parent job. Keep exits, shell options,
        variables and directory changes inside the business invocation. Do not
        put this command in an if/AND/OR list: that can disable errexit inside.
        Configuration fragments should use include_raw instead.
        """
        arguments = " ".join(shlex.quote(arg) for arg in args)
        workflow = config.workflow_mode
        inline = config.script_invoke_mode == "inline"
        if workflow == "ecflow":
            # ecFlow substitutes %NAME% even inside shell quotes. %% is a literal %.
            arguments = arguments.replace("%", "%%")
        elif workflow == "takler" and args:
            # Pass the quoted shell words through takler's Jinja render as a string literal.
            arguments = "{{ " + repr(arguments) + " }}"
        if inline:
            invocation = include_raw(script_path)
            if workflow == "takler":
                invocation = "{% raw %}\n" + invocation + "\n{% endraw %}"
            if args:
                invocation = f"set -- {arguments}\n{invocation}"
        else:
            _check_script_reference(script_path, output_repo_base, config, report,
                                    helper="invoke_script", stage="job.render")
            runtime_path = _runtime_reference(script_path)
            if not runtime_path:
                protect_input(Path(output_repo_base, script_path))
                if script_input_check is not None:
                    script_input_check(script_path)
            if environment is None and runtime_path:
                # The legacy renderer allows runtime references in the path.
                invocation = f'"${{OUTPUT_REPO_BASE}}/{script_path}"'
            else:
                invocation = '"${OUTPUT_REPO_BASE}"/' + shlex.quote(script_path)
            if args:
                invocation += f" {arguments}"
        if inline or workflow == "ecflow":
            if workflow in ("ecflow", "takler"):
                invocation = (
                    "# Give ksh93 a real subshell so the parent can handle signals.\n"
                    "case ${KSH_VERSION:-} in\n"
                    "    *93*) trap : 0; trap - 0 ;;\n"
                    "esac\n"
                    + invocation
                )
            # A comment-only marker task still needs a command inside (...).
            return f"(\n:\n{invocation}\n)\n"
        return invocation

    def build_environment(source_idx: int) -> Environment:
        """Build a Jinja2 env where the current source repo has highest priority.

        Search order: current source, then earlier layers in reverse rendering
        order (more specialised layers first).
        """
        source_repo_base = repo_bases[source_idx]
        search_paths = [source_repo_base]
        if source_idx > 0:
            search_paths.extend(repo_bases[source_idx - 1::-1])

        env = environment if environment is not None else Environment(
            loader=_JobTemplateLoader(search_paths, report),
            lstrip_blocks=True,
            trim_blocks=True,
        )
        env.globals["include_raw"] = include_raw
        env.globals["invoke_script"] = invoke_script
        env.globals.update(RESOURCE_TEMPLATE_HELPERS)
        return env

    if config.workflow_mode == "shell":
        output_file_suffix = "sh"
    elif config.workflow_mode == "ecflow":
        output_file_suffix = "ecf"
    elif config.workflow_mode == "takler":
        output_file_suffix = "sh"
    else:
        output_file_suffix = "sh"

    planned = []
    destinations = {}
    for source_idx, repo_base_str, jobs_dir in repo_jobs_pairs:
        env = build_environment(source_idx)
        j2_files = sorted(jobs_dir.rglob("*.j2"))
        for j2_file in j2_files:
            relative_path = j2_file.relative_to(repo_base_str)
            jobs_relative_path = j2_file.relative_to(jobs_dir)

            if template_filter is not None and not template_filter(jobs_relative_path):
                if verbose:
                    print(f"Skipped (disabled): {jobs_relative_path}")
                continue

            if jobs_relative_path.stem.endswith(".sh"):
                base_name = jobs_relative_path.stem[:-3]
            else:
                base_name = jobs_relative_path.stem

            output_file_relative_path = Path(
                job_output_dir,
                jobs_relative_path.parent,
                f"{base_name}.{output_file_suffix}",
            )
            destination = check_relative_path(output_repo_base, output_file_relative_path,
                                               stage="job.preflight", report=report)
            check_output_path(destination, stage="job.preflight", report=report)
            resolved = destination.resolve()
            for previous, previous_template in destinations.items():
                if resolved == previous and relative_path == previous_template:
                    continue  # Declared later-layer override of the same template.
                if resolved == previous or resolved in previous.parents or previous in resolved.parents:
                    report.fail("GEN_JOB_NAME_COLLISION", "job.preflight",
                                output_file_relative_path.as_posix(),
                                "different job templates map to conflicting output paths")
            destinations[resolved] = relative_path
            planned.append((env, relative_path, output_file_relative_path))

    if environment is not None:
        # The supplied standard loader searches the final effective layer set.
        # Shadowed templates must neither render nor fail on obsolete inputs.
        planned = list({destination: (env, relative, destination)
                        for env, relative, destination in planned}.values())
    files = [(source, Path(output_repo_base, target))
             for env, relative, target in planned
             if (source := _template_file(env, relative.as_posix())) is not None]
    protect_input = _job_input_guard(destinations, report)
    for source, _ in files:
        protect_input(source)
    if prepare_outputs is not None:
        prepare_outputs(files)

    for env, relative_path, output_file_relative_path in planned:
        _render_single_job_file(
            relative_path=relative_path,
            output_repo_base=output_repo_base,
            output_relative_path=output_file_relative_path,
            config=config,
            env=env,
            report=report,
            template_context=template_context,
            file_mode=file_mode,
        )

        if verbose:
            print(f"Generated: {output_file_relative_path}")


def render_single_job_file(
    relative_path: Path,
    output_repo_base: str,
    output_relative_path: Path,
    config: "BaseWorkflowConfig",
    env: Environment,
    *,
    check_report: Optional[GenerationCheckReport] = None,
):
    """Render one job template file into the output repo (executable)."""
    report = check_report if check_report is not None else GenerationCheckReport()
    preflight_generation(config, check_report=report)
    destination = check_relative_path(output_repo_base, output_relative_path,
                                      stage="job.preflight", report=report)
    check_output_path(destination, stage="job.preflight", report=report)
    for name, helper in RESOURCE_TEMPLATE_HELPERS.items():
        env.globals.setdefault(name, helper)
    source = _template_file(env, relative_path.as_posix())
    if source is not None:
        _job_input_guard([destination], report)(source)
    _render_single_job_file(relative_path, output_repo_base, output_relative_path, config, env, report)


def _render_single_job_file(
    relative_path: Path, output_repo_base: str, output_relative_path: Path,
    config: "BaseWorkflowConfig", env: Environment, report: GenerationCheckReport,
    *, template_context: Mapping | None = None, file_mode: int | None = None,
) -> None:
    base_name = output_relative_path.stem
    if file_mode is not None and config.workflow_mode == "shell":
        from takflow._files import make_parents
        make_parents(Path(output_repo_base) / "logs/.log", Path(output_repo_base))
    output_log_dict = generate_output_log_data(
        config=config,
        name=base_name,
        output_repo_base=output_repo_base,
    )

    build_info_lines = _current_build_info_lines()
    data = {
        **(template_context or {}),
        "config": config,
        "build_info_warning": build_info_lines["warning"],
        "build_info_detail": build_info_lines["info"],
        **output_log_dict,
    }

    try:
        template = env.get_template(relative_path.as_posix())
        rendered_content = template.render(data)
    except GenerationCheckError:
        raise
    except (TemplateError, TypeError, ValueError, OSError) as error:
        subject, reason = template_failure(relative_path, env, error)
        if file_mode is not None:
            report.failed("GEN_JOB_RENDER", "job.render", subject, reason)
            raise
        report.fail("GEN_JOB_RENDER", "job.render", subject, reason)

    output_file_path = Path(output_repo_base, output_relative_path)
    try:
        if file_mode is not None:
            from takflow._files import write_text
            write_text(output_file_path, rendered_content, file_mode, Path(output_repo_base))
            report.artifact(output_file_path, "job", stage="job.output")
            return
        output_file_path.parent.mkdir(exist_ok=True, parents=True)
        with open(output_file_path, "w") as f:
            f.write(rendered_content)
        mode = os.stat(output_file_path).st_mode
        os.chmod(output_file_path, mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    except OSError as error:
        reason = io_failure_reason("job output could not be written or its permissions could not be set", error)
        if file_mode is not None:
            report.failed("GEN_JOB_WRITE", "job.output", output_relative_path.as_posix(), reason)
            raise
        report.fail("GEN_JOB_WRITE", "job.output", output_relative_path.as_posix(), reason)
    report.artifact(output_file_path, "job", stage="job.output")


def generate_output_log_data(
    config: "BaseWorkflowConfig", name: str, output_repo_base: str
) -> Dict[str, str]:
    """Compute stdout/stderr log path template data for a job by mode/workload."""
    if config.workflow_mode == "ecflow":
        output = "%ECF_JOBOUT%"
        error = "%ECF_JOBOUT%.err"
    elif config.workflow_mode == "takler":
        output = "{{ TAKLER_JOBOUT }}"
        error = "{{ TAKLER_JOBOUT }}.err"
    else:
        logs = Path(output_repo_base, "logs")
        logs.mkdir(parents=True, exist_ok=True)
        suffix = ".%j" if config.workload.workload_type == "slurm" else ""
        output = str(logs / f"{name}{suffix}.out")
        error = str(logs / f"{name}{suffix}.err")
    return {"output_std_log_path": output, "output_stderr_log_path": error}


