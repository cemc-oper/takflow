"""Generic build-info header generation.

Apps bind a tool name + version; takflow renders the standard
``AUTO-GENERATED`` warning and the ``Generated by <tool> v<ver> at <ts>`` line
injected into every generated file.
"""
from __future__ import annotations

from datetime import datetime, timezone
from contextlib import contextmanager
from contextvars import ContextVar
from collections.abc import Callable, Mapping

from pydantic import BaseModel


_scoped_lines: ContextVar[Mapping[str, str] | None] = ContextVar("takflow_build_info", default=None)
_build_info_provider: Callable[[], dict[str, str]] | None = None


@contextmanager
def build_info_scope(lines: Mapping[str, str]):
    """Supply explicit build headers without replacing the legacy provider."""
    token = _scoped_lines.set(dict(lines))
    try:
        yield
    finally:
        _scoped_lines.reset(token)


class BuildInfo(BaseModel):
    """Build metadata.

    Attributes
    ----------
    build_time : datetime
        Build time (UTC).
    version : str
        Version string.
    """

    build_time: datetime
    version: str


def get_build_info(version: str) -> BuildInfo:
    """Return a :class:`BuildInfo` stamped now (UTC) with ``version``."""
    return BuildInfo(build_time=datetime.now(timezone.utc), version=version)


def get_build_info_lines(build_info: BuildInfo, tool_name: str) -> dict[str, str]:
    """Render the standard header lines for ``tool_name``.

    Returns a dict with ``"warning"`` and ``"info"`` keys.
    """
    ts = build_info.build_time.strftime("%Y-%m-%dT%H:%M:%SZ")
    return {
        "warning": "AUTO-GENERATED FILE - DO NOT EDIT. Changes will be overwritten.",
        "info": f"Generated by {tool_name} v{build_info.version} at {ts}",
    }


def set_build_info_provider(provider: Callable[[], dict[str, str]]) -> None:
    """Register the fallback header provider for standalone job rendering."""
    global _build_info_provider
    _build_info_provider = provider


def _current_build_info_lines() -> dict[str, str]:
    scoped = _scoped_lines.get()
    if scoped is not None:
        return dict(scoped)
    if _build_info_provider is not None:
        return _build_info_provider()
    return get_build_info_lines(get_build_info("unknown"), "takflow")


__all__ = ["BuildInfo", "get_build_info", "get_build_info_lines", "build_info_scope", "set_build_info_provider"]
